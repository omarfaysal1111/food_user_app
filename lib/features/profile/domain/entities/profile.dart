class Profile {
  final String id;
  final String firstName;
  final String lastName;
  final String fullName;
  final String phone;
  final String email;
  final String avatar;
  final String locale;

  const Profile({
    required this.id,
    required this.firstName,
    required this.lastName,
    required this.fullName,
    required this.phone,
    required this.email,
    required this.avatar,
    required this.locale,
  });
}
